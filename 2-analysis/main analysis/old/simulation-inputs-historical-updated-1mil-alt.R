#Analytically solve beta for each age and risk group (using nonsevere risk model EQ)
beta_analytic_calibration <- function() {
  
  
  #Dynamic term (Age-specific only)
  dynamic_term <- rep(c(sum((inf_by_age$total_inf/inf_by_age$total_pop) * contact_matrix$X0.17.years),
                        sum((inf_by_age$total_inf/inf_by_age$total_pop) * contact_matrix$X18.29.years),
                        sum((inf_by_age$total_inf/inf_by_age$total_pop) * contact_matrix$X30.49.years),
                        sum((inf_by_age$total_inf/inf_by_age$total_pop) * contact_matrix$X50.64.years),
                        sum((inf_by_age$total_inf/inf_by_age$total_pop) * contact_matrix$X65.74.years),
                        sum((inf_by_age$total_inf/inf_by_age$total_pop) * contact_matrix$X75..years)), 
                      each = 3)
  
  #Average nonsevere risk (with immunity offset) and nonsevere protection at model start, by age and risk group
  nonsevere_risk_and_protection <- merge(protection_at_model_init[[4]], average_nonsevere_incidence, by = c("age_group", "risk_group"), all.x = TRUE) %>%
    mutate(nonsevere_risk = (nonsevere_inc/100000)/7, #convert weekly nonsevere incidence (per 100,000) into per-person daily risk
           immunity_offset = (1 - mean_severe_ve)/(1 - mean_nonsevere_ve), #immunity offset by age and risk group (different from the one used for I_jt)
           nonsevere_risk_adj = nonsevere_risk / immunity_offset) #Adjust the per-person daily nonsevere risk for immunity offset at model initialization
  
  
  
  #Betas vector (to populate)
  beta_vector <- c()
  
  #Analytically solve for each beta
  for(i in c(1:18)) {
    
    beta_vector[i] <- nonsevere_risk_and_protection$nonsevere_risk_adj[i]/((1-nonsevere_risk_and_protection$mean_nonsevere_ve[i]) * dynamic_term[i])
    print(beta_vector[i])
    
  }
  
  nonsevere_risk_and_protection$betas <- beta_vector
  return(nonsevere_risk_and_protection %>% select(age_group, risk_group, betas))
}

beta <- setDT(beta_analytic_calibration())
setkeyv(beta, c("age_group", "risk_group"))

