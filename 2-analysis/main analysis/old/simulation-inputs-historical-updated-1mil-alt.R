#I_jt at model start: Estimate the total currently circulating infections @ t = 0 using the average severe incidences
inf_by_age <- merge(merge(merge(clean_df[[1]] %>% group_by(age_group, risk_group) %>% summarise(total_pop = n()),
                                average_severe_incidence, by = c("age_group", "risk_group"), all.x = TRUE),
                          average_nonsevere_incidence, by = c("age_group", "risk_group"), all.x = TRUE),
                    immunity_offset_mult, by = "age_group", all.x = TRUE) %>% 
  mutate(severe_inf = (total_pop * severe_inc/100000)/7, #dividing by 7 to convert weekly to daily 
         inverse_severe_mult = nonsevere_inc/severe_inc) %>% #age-specific severe multiplier (weighted by risk group) to convert severe cases to total cases
  group_by(age_group) %>%
  summarise(weighted_severe_mult_inverse = weighted.mean(inverse_severe_mult, total_pop),
            severe_inf = sum(severe_inf),
            total_pop = sum(total_pop),
            immunity_offset = mean(immunity_offset)) %>%
  mutate(total_inf = ceiling((severe_inf) * weighted_severe_mult_inverse * immunity_offset * 5) +
           ceiling(severe_inf * 5)) %>%  #multiplying by 5 because infectious period is 5 days
  select(age_group, total_pop, total_inf)

